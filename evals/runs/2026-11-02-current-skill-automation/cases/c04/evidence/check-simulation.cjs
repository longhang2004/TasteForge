const fs = require("node:fs");
const vm = require("node:vm");
const assert = require("node:assert/strict");
const fixture = JSON.parse(fs.readFileSync("fixture.json", "utf8"));
const handlers = {};
const elements = {};
for (const id of ["subtotal-label", "subtotal", "total"]) elements[id] = { textContent: "" };
const status = { textContent: "", classList: { add() {}, remove() {} } };
const quantity = { value: "1" };
const form = { elements: { glaze: { value: "iron" } }, addEventListener: (event, callback) => handlers[event] = callback };
const document = { getElementById: id => id === "order-form" ? form : id === "quantity" ? quantity : elements[id], querySelector: () => status };
vm.runInNewContext(fs.readFileSync("app.js", "utf8"), { document });
handlers.change();
assert.equal(elements.total.textContent, "USD 76.00");
form.elements.glaze.value = "sand";
quantity.value = "2";
handlers.change();
assert.equal(elements.total.textContent, "USD 144.00");
assert.equal(2 * fixture.priceUSD + fixture.shippingUSD, 144);
handlers.submit({ preventDefault() {} });
assert.match(status.textContent, /2 × Everyday Teapot, Sand glaze/);
assert.match(status.textContent, /USD 144.00/);
form.elements.glaze.value = "ash";
handlers.submit({ preventDefault() {} });
assert.match(status.textContent, /Choose an available glaze/);
console.log("PASS: application logic in stub DOM: Iron x1 = USD 76.00; Sand x2 = USD 144.00; selected glaze/quantity confirmation; Ash submit rejected. This is not a browser interaction test.");
